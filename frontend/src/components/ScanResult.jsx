
import "./ScanResult.css";

function ScanResult({ result }) {
  if (!result) return null;

  function downloadReport() {
    const report = `
TRUSTSHIELD AI - WEBSITE SECURITY REPORT
========================================

Website: ${result.url || "Not provided"}
Scan Date: ${result.scannedAt || new Date().toLocaleString()}

RISK ASSESSMENT
---------------
Risk Score: ${result.score}/100
Risk Level: ${result.level}

SECURITY ANALYSIS
-----------------
Phishing Detection: ${result.phishing}
SSL Certificate: ${result.ssl}
Website Security: ${result.security}

ANALYSIS EXPLANATION
--------------------
${result.explanation}

========================================
Generated by TrustShield AI
Detect. Verify. Stay Safe.
`;

    const blob = new Blob([report], {
      type: "text/plain",
    });

    const link = document.createElement("a");
    const url = URL.createObjectURL(blob);

    link.href = url;
    link.download = "TrustShield_Security_Report.txt";

    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    URL.revokeObjectURL(url);
  }

  return (
    <div className="result-container">
      <h2>Website Security Report</h2>

      <div className="risk-card">
        <p>Website Risk Score</p>
        <h1>{result.score}/100</h1>
        <span className="risk-level">
          {result.level} RISK
        </span>
      </div>

      <div className="security-details">
        <div className="security-item">
          <h3>Phishing Detection</h3>
          <p>{result.phishing}</p>
        </div>

        <div className="security-item">
          <h3>SSL Certificate</h3>
          <p>{result.ssl}</p>
        </div>

        <div className="security-item">
          <h3>Website Security</h3>
          <p>{result.security}</p>
        </div>
      </div>

      <div className="explanation">
        <h3>Analysis Explanation</h3>
        <p>{result.explanation}</p>
      </div>

      <button
        className="download-report-btn"
        onClick={downloadReport}
      >
        Download Security Report
      </button>
    </div>
  );
}

export default ScanResult;
