
import "./ScanResult.css";

function ScanResult({ result }) {
  if (!result) return null;

  const ssl = result.sslDetails;
  const website = result.websiteSecurity;
  const domain = website?.domain;

  const score = Math.max(
    0,
    Math.min(100, Number(result.score) || 0)
  );

  const level =
    result.level ||
    (score >= 60 ? "HIGH" : score >= 30 ? "MEDIUM" : "LOW");

  const riskClass = level.toLowerCase();

  function downloadReport() {
    const report = `
TRUSTSHIELD AI - SECURITY REPORT
================================

Website: ${result.url || "Not provided"}
Date: ${result.scannedAt || new Date().toLocaleString()}

RISK ASSESSMENT
Risk Score: ${score}/100
Risk Level: ${level}

PHISHING DETECTION
${result.phishing || "Unknown"}

SSL CERTIFICATE
Status: ${result.ssl || "Unknown"}
Issuer: ${ssl?.issuer || "Unknown"}
Expiry: ${ssl?.expires_on || "Unknown"}
Days Remaining: ${ssl?.days_remaining ?? "Unknown"}

DOMAIN ANALYSIS
Domain: ${domain?.hostname || "Unknown"}
Domain Age: ${website?.domain_age_days ?? "Unknown"} days
Suspicious TLD: ${domain?.suspicious_tld ?? "Unknown"}

SECURITY ISSUES
${
  website?.issues?.map(issue =>
    `- ${issue.message} (${issue.severity}, ${issue.points} points)`
  ).join("\n") || "No issues reported"
}

EXPLANATION
${result.explanation || "No explanation available"}

================================
Generated by TrustShield AI
`;

    const blob = new Blob([report], {
      type: "text/plain",
    });

    const downloadUrl = URL.createObjectURL(blob);
    const link = document.createElement("a");

    link.href = downloadUrl;
    link.download = "TrustShield_Security_Report.txt";
    link.click();

    URL.revokeObjectURL(downloadUrl);
  }

  return (
    <div className="result-container">

      {/* REPORT HEADER */}
      <div className="report-header">
        <div>
          <span className="report-eyebrow">
            TRUSTSHIELD AI / SECURITY ANALYSIS
          </span>

          <h2>Website Security Report</h2>

          <p className="report-url">
            {result.url}
          </p>
        </div>

        <div className="report-complete">
          <span className="complete-dot"></span>
          Analysis Complete
        </div>
      </div>

      {/* SPEEDOMETER */}
      <section className={`risk-card ${riskClass}`}>

        <div className="risk-card-heading">
          <div>
            <span className="section-label">
              OVERALL RISK ASSESSMENT
            </span>

            <h3>Website Risk Score</h3>
          </div>

          <span className={`risk-level ${riskClass}`}>
            {level} RISK
          </span>
        </div>

        <div className="speedometer">

          <svg
            viewBox="0 0 280 175"
            className="speedometer-svg"
            role="img"
            aria-label={`Risk score ${score} out of 100`}
          >

            {/* Background track */}
            <path
              d="M 30 140 A 110 110 0 0 1 250 140"
              className="gauge-track"
            />

            {/* Green zone */}
            <path
              d="M 30 140 A 110 110 0 0 1 250 140"
              pathLength="100"
              strokeDasharray="30 70"
              strokeDashoffset="0"
              className="gauge-green"
            />

            {/* Amber zone */}
            <path
              d="M 30 140 A 110 110 0 0 1 250 140"
              pathLength="100"
              strokeDasharray="30 70"
              strokeDashoffset="-30"
              className="gauge-amber"
            />

            {/* Red zone */}
            <path
              d="M 30 140 A 110 110 0 0 1 250 140"
              pathLength="100"
              strokeDasharray="40 60"
              strokeDashoffset="-60"
              className="gauge-red"
            />

            {/* Needle */}
            <line
              x1="140"
              y1="140"
              x2="140"
              y2="43"
              className="gauge-needle"
              style={{
                transform: `rotate(${-90 + score * 1.8}deg)`,
                transformOrigin: "140px 140px",
              }}
            />

            <circle
              cx="140"
              cy="140"
              r="9"
              className="gauge-center"
            />

            {/* Score */}
            <text
              x="140"
              y="110"
              textAnchor="middle"
              className="gauge-score"
            >
              {score}
            </text>

            <text
              x="140"
              y="128"
              textAnchor="middle"
              className="gauge-score-label"
            >
              OUT OF 100
            </text>

            {/* Labels */}
            <text x="23" y="164" className="gauge-label">
              LOW
            </text>

            <text
              x="140"
              y="18"
              textAnchor="middle"
              className="gauge-label"
            >
              MEDIUM
            </text>

            <text
              x="257"
              y="164"
              textAnchor="end"
              className="gauge-label"
            >
              HIGH
            </text>

          </svg>

          <p className="gauge-description">
            {score < 30
              ? "No major risk indicators detected."
              : score < 60
              ? "Some security concerns require attention."
              : "Significant security risks detected."}
          </p>

        </div>

      </section>

      {/* SECURITY OVERVIEW */}
      <section className="report-section">

        <div className="section-heading">
          <span className="section-label">01 / SECURITY OVERVIEW</span>
          <h3>Security Assessment</h3>
        </div>

        <div className="security-details">

          <div className="security-item">
            <span className="item-icon">01</span>
            <div>
              <span className="item-label">
                Phishing Detection
              </span>
              <h4>{result.phishing || "Unknown"}</h4>
            </div>
          </div>

          <div className="security-item">
            <span className="item-icon">02</span>
            <div>
              <span className="item-label">
                SSL Certificate
              </span>
              <h4>{result.ssl || "Unknown"}</h4>
            </div>
          </div>

          <div className="security-item">
            <span className="item-icon">03</span>
            <div>
              <span className="item-label">
                Website Security
              </span>
              <h4>{result.security || "Unknown"}</h4>
            </div>
          </div>

        </div>

      </section>

      {/* SSL DETAILS */}
      {ssl && (
        <section className="report-section">

          <div className="section-heading">
            <span className="section-label">02 / ENCRYPTION</span>
            <h3>SSL Certificate Details</h3>
          </div>

          <div className="detail-grid">

            <div className="detail-box">
              <span>Certificate Issuer</span>
              <strong>{ssl.issuer || "Unknown"}</strong>
            </div>

            <div className="detail-box">
              <span>Expiry Date</span>
              <strong>{ssl.expires_on || "Unknown"}</strong>
            </div>

            <div className="detail-box">
              <span>Days Remaining</span>
              <strong>{ssl.days_remaining ?? "Unknown"}</strong>
            </div>

            <div className="detail-box">
              <span>Certificate Status</span>
              <strong>{ssl.status || "Unknown"}</strong>
            </div>

          </div>

        </section>
      )}

      {/* DOMAIN ANALYSIS */}
      {website && (
        <section className="report-section">

          <div className="section-heading">
            <span className="section-label">03 / DOMAIN INTELLIGENCE</span>
            <h3>Domain Analysis</h3>
          </div>

          <div className="detail-grid">

            <div className="detail-box">
              <span>Hostname</span>
              <strong>{domain?.hostname || "Unknown"}</strong>
            </div>

            <div className="detail-box">
              <span>Domain Age</span>
              <strong>
                {website.domain_age_days ?? "Unknown"} days
              </strong>
            </div>

            <div className="detail-box">
              <span>Suspicious TLD</span>
              <strong>
                {domain?.suspicious_tld ? "Yes" : "No"}
              </strong>
            </div>

            <div className="detail-box">
              <span>IP Address URL</span>
              <strong>
                {domain?.is_ip_address ? "Yes" : "No"}
              </strong>
            </div>

          </div>

        </section>
      )}

      {/* SECURITY ISSUES */}
      {website?.issues?.length > 0 && (
        <section className="report-section">

          <div className="section-heading">
            <span className="section-label">04 / THREAT INDICATORS</span>
            <h3>Security Issues</h3>
          </div>

          <div className="issues-list">

            {website.issues.map((issue, index) => (
              <div className="issue-card" key={index}>

                <div className="issue-top">
                  <h4>{issue.category || "Security Issue"}</h4>

                  <span
                    className={`severity-tag ${
                      issue.severity?.toLowerCase() || "unknown"
                    }`}
                  >
                    {issue.severity || "Unknown"}
                  </span>
                </div>

                <p>{issue.message}</p>

                <span className="issue-points">
                  Risk points: {issue.points}
                </span>

              </div>
            ))}

          </div>

        </section>
      )}

      {/* EXPLANATION */}
      <section className="report-section">

        <div className="section-heading">
          <span className="section-label">05 / FINAL ANALYSIS</span>
          <h3>Analysis Explanation</h3>
        </div>

        <div className="final-explanation">
          <p>
            {result.explanation ||
              "No additional explanation available."}
          </p>
        </div>

      </section>

      {/* FOOTER */}
      <div className="report-footer">

        <div>
          <strong>TRUSTSHIELD AI</strong>
          <span>Intelligent Website Security Analysis</span>
        </div>

        <button
          className="download-report-btn"
          onClick={downloadReport}
        >
          Download Report ↗
        </button>

      </div>

    </div>
  );
}

export default ScanResult;
